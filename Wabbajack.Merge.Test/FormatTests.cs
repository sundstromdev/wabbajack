using Xunit;

namespace Wabbajack.Merge.Test;

public class FormatTests
{
    [Fact]
    public void ModListTxtReadsLowestPriorityFirstAndWritesBack()
    {
        const string text = "# This file was automatically generated by Mod Organizer.\r\n+Top\r\n-Middle\r\n*Unmanaged: DLC\r\n+Bottom_separator";
        var asc = Mo2ModList.ParseAscending(text, out var comments);
        Assert.Equal(new[] { "+Bottom_separator", "*Unmanaged: DLC", "-Middle", "+Top" }, asc.Select(e => e.ToString()));
        Assert.True(asc[0].IsSeparator);
        Assert.False(asc[2].Enabled);
        Assert.Equal(text, Mo2ModList.WriteAscending(asc, comments));
    }

    [Fact]
    public void ModListTxtToleratesLfAndBlankLines()
    {
        var asc = Mo2ModList.ParseAscending("+B\n\n+A\n", out _);
        Assert.Equal(new[] { "A", "B" }, asc.Select(e => e.Name));
        Assert.Equal(1, Mo2ModList.IndexOf(asc, "b"));
        Assert.Equal(-1, Mo2ModList.IndexOf(asc, "C"));
    }

    [Fact]
    public void IniSectionsAreSplitVerbatim()
    {
        var sections = IniSections.Split("; header comment\n[A]\nx = 1\n\n[B.C]\ny = 2\n");
        Assert.Equal(new[] { "A", "B.C" }, sections.Select(s => s.Name));
        Assert.Equal("[A]\nx = 1", sections[0].Text);
    }

    [Fact]
    public void AppendingKeepsTheTargetsLineEndingsAndRefusesUnknownSections()
    {
        var (text, added) = IniSections.AppendMissing("[A]\r\nx = 1\r\n", "[A]\nx = 9\n[B]\ny = 2\n", Array.Empty<string>());
        Assert.Equal("[A]\r\nx = 1\r\n\r\n[B]\r\ny = 2\r\n", text);
        Assert.Equal(new[] { "B" }, added);

        var (same, none) = IniSections.AppendMissing("[A]\nx = 1\n", "[A]\nx = 2\n", Array.Empty<string>());
        Assert.Equal("[A]\nx = 1\n", same);
        Assert.Empty(none);

        Assert.Throws<MergeException>(() => IniSections.AppendMissing("", "[A]\n", new[] { "Z" }));
    }
}

public class MergePlannerTests
{
    [Fact]
    public void DraftTakesNewModsAndListsSharedAndDuplicates()
    {
        var b = new ListBuilder("Base List").Separator("Core_separator").Mod("CET", 107, "a.dll")
            .Mod("Map Fix", 23420, "m.archive").Profile("Main", "+Core_separator", "+CET", "+Map Fix").Build();
        var o = new ListBuilder("Project Ultrapunk").Separator("Visual_separator").Mod("CET", 107, "a.dll")
            .Mod("Nova", 12490, "n.archive").Mod("Map Nuclear Fix", 23420, "m.archive")
            .Profile("1. Low", "+Visual_separator", "+CET", "+Nova", "+Map Nuclear Fix")
            .Profile("2. High", "+Visual_separator", "+CET", "+Nova", "-Map Nuclear Fix").Build();

        var (rules, plan) = MergePlanner.Draft(b, o, null);
        Assert.Equal("2. High", rules.OverlayProfile);
        Assert.Equal(new[] { "Nova" }, rules.Include.Mods);
        Assert.Equal("PU ", rules.SeparatorPrefix);
        Assert.NotNull(rules.CyberpunkArchiveLoadOrder);
        Assert.Contains("[shared] CET", plan);
        Assert.Contains("[duplicate of Map Fix]", plan);
        Assert.Contains("`Core_separator`", plan);

        Assert.Throws<MergeException>(() => MergePlanner.Draft(b, o, "3. Missing"));
        Assert.Equal("1. Low", MergePlanner.Draft(b, o, "1. Low").Rules.OverlayProfile);
    }

    [Fact]
    public void ADraftRoundTripsThroughJson()
    {
        var b = new ListBuilder("B").Mod("A", 1, "a.txt").Profile("P", "+A").Build();
        var o = new ListBuilder("O").Mod("V", 2, "v.txt").Profile("Q", "+V").Build();
        var (rules, _) = MergePlanner.Draft(b, o, null);
        var again = MergeRules.Parse(rules.ToJson());
        Assert.Equal(rules.Include.Mods, again.Include.Mods);
        Assert.Equal(rules.OverlayProfile, again.OverlayProfile);
        Assert.Equal(rules.InsertBefore, again.InsertBefore);
    }
}
